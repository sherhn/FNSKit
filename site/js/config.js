// Адрес API для фронтенда.
//
// В продакшене статику и процессор отдаёт один и тот же nginx, поэтому ходим
// на собственный origin: домена в коде нет, CORS не нужен.
//
// Локальная разработка (файл, открытый напрямую, или статик-сервер IDE)
// продолжает стучаться прямо в контейнер процессора — там origin другой, и
// заменять адрес нельзя. Такие запуски узнаём по протоколу file: и по портам
// статик-серверов. Порта 8082 в списке нет: это сам nginx из docker compose, он
// проксирует API, а прямой запрос к :8080 запретила бы его же CSP
// (connect-src 'self').
(() => {
  const DEV_PORTS = new Set(["63342", "8765", "5500", "3000"]);

  if (location.protocol === "file:" || DEV_PORTS.has(location.port)) return;

  window.FNSKIT_PROCESSOR_API = "/api/processor";
})();
